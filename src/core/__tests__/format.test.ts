import { describe, expect, it } from "vitest";
import { DEFAULT_OPTIONS, fmtInt, fmtPct, fmtPf, sizeTransformers, type RawLoadRow } from "..";

describe("number display rules (page and Excel)", () => {
  it("whole numbers with thousands separators", () => {
    expect(fmtInt(3006.2)).toBe("3,006");
    expect(fmtInt(3006.5)).toBe("3,007");
    expect(fmtInt(0.4)).toBe("0");
    expect(fmtInt(-0.2)).toBe("0"); // never "-0"
    expect(fmtInt(2000)).toBe("2,000");
    expect(fmtInt(23400)).toBe("23,400");
  });
  it("percentages have exactly one decimal", () => {
    expect(fmtPct(45.234)).toBe("45.2");
    expect(fmtPct(80)).toBe("80.0");
    expect(fmtPct(99.96)).toBe("100.0");
    expect(fmtPct(1234.56)).toBe("1,234.6");
  });
  it("power factor keeps two decimals", () => {
    expect(fmtPf(0.7)).toBe("0.70");
    expect(fmtPf(0.9)).toBe("0.90");
    expect(fmtPf(0.7861)).toBe("0.79");
  });
  it("messages generated by the calculation follow the same rules (no stray decimals on kVA)", () => {
    const rows: RawLoadRow[] = [1000, 1000, 1000, 1000, 1000].map((kva, i) => ({
      rowNumber: i + 2, description: `L${i}`, type: "Feeder", voltageV: 433, amps: (kva * 1000) / (Math.sqrt(3) * 420),
    }));
    const r = sizeTransformers(rows, 433, { ...DEFAULT_OPTIONS, ratingsKva: [2000] });
    const notes = r.combos.flatMap((c) => c.notes);
    expect(notes.length).toBeGreaterThan(0);
    for (const n of notes) expect(n, n).not.toMatch(/\d\.\d+ kVA/); // no decimals on kVA
    expect(notes.join(" ")).toMatch(/80\.0 % normal limit of 1,600 kVA/);
    const big = sizeTransformers([{ rowNumber: 2, description: "Big", type: "Feeder", voltageV: 433, amps: (1700 * 1000) / (Math.sqrt(3) * 420) }], 433, { ...DEFAULT_OPTIONS, ratingsKva: [2000] });
    expect(big.blockers[0]).toBe("Big (row 2, 1,700 kVA) is larger than one transformer section can carry: 80.0 % of 2,000 kVA = 1,600 kVA.");
  });
});
